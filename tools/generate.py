#!/usr/bin/env python3
"""Generate typed wire descriptors from the audited protocol inventory.

Writes src/methods.rs, tests/wire_types.rs and tests/fixtures/all.xml, which are
checked in; consumers need neither Python nor an OpenRazer checkout. The XML
fixture is a synthetic protocol regression oracle, not a real device.
"""
import collections
import json
import pathlib
import re
import subprocess
from xml.etree.ElementTree import Element, SubElement, tostring

REPOSITORY = pathlib.Path(__file__).resolve().parent.parent

BASIC_TYPES = {
    'b': 'bool',
    'd': 'f64',
    'i': 'i32',
    'q': 'u16',
    's': 'String',
    'y': 'u8',
}

WIRE_TEST_PRELUDE = '''\
// Generated by tools/generate.py
use openrazer::{Method, methods::*};

fn check<I, O>(method: &Method<I, O>)
where
    I: Default + serde::Serialize + zbus::wire::DynamicType,
    O: Default + serde::Serialize + zbus::wire::DynamicType,
{
    let _input = zbus::Message::method_call("/test", "Test").build(&I::default()).unwrap();
    let _output = zbus::Message::method_call("/test", "Test").build(&O::default()).unwrap();
    assert_eq!(
        I::default().signature().to_string_no_parens(),
        method.info().input,
        "input {:?}",
        method.info()
    );
    assert_eq!(
        O::default().signature().to_string_no_parens(),
        method.info().output,
        "output {:?}",
        method.info()
    );
}

#[test]
fn every_binding_serializes_exact_wire_argument_lists() {
'''


def split_signature(signature):
    """Yield each complete D-Bus type of an argument-list signature."""
    while signature:
        end = 0
        while signature[end] == 'a':
            end += 1
        if signature[end] == '(':
            depth = 1
            end += 1
            while depth:
                depth += (signature[end] == '(') - (signature[end] == ')')
                end += 1
        else:
            end += 1
        yield signature[:end]
        signature = signature[end:]


def rust_type(signature):
    """The Rust type of one complete D-Bus type."""
    if signature.startswith('a'):
        return f'Vec<{rust_type(signature[1:])}>'
    if signature.startswith('('):
        return rust_tuple(signature[1:-1])
    return BASIC_TYPES[signature]


def rust_tuple(signature):
    """The Rust tuple of a signature's members; one member keeps its comma."""
    members = [rust_type(member) for member in split_signature(signature)]
    trailing = ',' if len(members) == 1 else ''
    return f'({", ".join(members)}{trailing})'


def constant_name(method):
    """`getDPIStages` becomes `GET_DPI_STAGES`."""
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', method['name'])
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).upper()


def module_name(interface):
    return interface.removeprefix('razer.').replace('.', '_')


def descriptor(method):
    interface, name = method['interface'], method['name']
    input_signature, output_signature = method['input'], method['output']
    return (
        f'/// `{interface}.{name}`: `{input_signature}` → `{output_signature}`.\n'
        f'pub const {constant_name(method)}: '
        f'Method<{rust_tuple(input_signature)}, {rust_tuple(output_signature)}> = '
        f'Method::new("{interface}", "{name}", "{input_signature}", "{output_signature}");'
    )


def methods_source(groups):
    items = [
        '//! Generated by tools/generate.py; protocol facts from docs/protocol.json.\n'
        '#![allow(clippy::type_complexity)]'
    ]
    names = []
    for module, methods in groups.items():
        constants = '\n\n'.join(descriptor(method) for method in methods)
        items.append(f'pub mod {module} {{\nuse crate::Method;\n\n{constants}\n}}')
        names += [f'{module}::{constant_name(method)}.info()' for method in methods]
    items.append(
        '/// Every audited method, including optional and legacy methods.\n'
        f'pub const ALL: &[crate::MethodInfo] = &[{", ".join(names)}];'
    )
    return '\n\n'.join(items) + '\n'


def wire_test_source(groups):
    checks = [
        f'check(&{module}::{constant_name(method)});'
        for module, methods in groups.items()
        for method in methods
    ]
    return WIRE_TEST_PRELUDE + '\n'.join(checks) + '\n}\n'


def introspection_fixture(groups):
    node = Element('node')
    for methods in groups.values():
        interface = SubElement(node, 'interface', name=methods[0]['interface'])
        for method in methods:
            element = SubElement(interface, 'method', name=method['name'])
            for direction, key in [('in', 'input'), ('out', 'output')]:
                for signature in split_signature(method[key]):
                    SubElement(element, 'arg', type=signature, direction=direction)
    return tostring(node, encoding='unicode') + '\n'


def main():
    inventory = json.loads((REPOSITORY / 'docs/protocol.json').read_text())
    groups = collections.defaultdict(list)
    for method in inventory['methods']:
        groups[module_name(method['interface'])].append(method)

    (REPOSITORY / 'src/methods.rs').write_text(methods_source(groups))
    (REPOSITORY / 'tests/wire_types.rs').write_text(wire_test_source(groups))
    (REPOSITORY / 'tests/fixtures/all.xml').write_text(introspection_fixture(groups))
    subprocess.run(['cargo', 'fmt'], cwd=REPOSITORY, check=True)


if __name__ == '__main__':
    main()
