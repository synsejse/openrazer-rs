#!/usr/bin/env python3
"""Generate typed wire descriptors from the audited protocol inventory."""
import collections
import json
import pathlib
import re
import subprocess

inventory = json.loads(pathlib.Path('docs/protocol.json').read_text())
def types(sig):
    result=[]
    while sig:
        c,sig=sig[0],sig[1:]
        if c=='a':
            children,rest=one(sig); result.append('Vec<'+children+'>');sig=rest
        elif c=='(':
            depth=1;i=0
            while depth:
                if sig[i]=='(':depth+=1
                if sig[i]==')':depth-=1
                i+=1
            result.append(tup(types(sig[:i-1])));sig=sig[i:]
        else: result.append({'y':'u8','q':'u16','i':'i32','d':'f64','b':'bool','s':'String'}[c])
    return result

def one(sig):
    if sig[0]=='(':
        depth=0
        for i,c in enumerate(sig):
            depth+=(c=='(')-(c==')')
            if depth==0:return types(sig[:i+1])[0],sig[i+1:]
    return types(sig[0])[0],sig[1:]

def tup(ts):return '('+','.join(ts)+(',' if ts else '')+')'
def snake(s):
    s=re.sub(r'([A-Z]+)([A-Z][a-z])',r'\1_\2',s)
    return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',s).lower()

groups=collections.defaultdict(list)
for m in inventory['methods']:groups[m['interface'].removeprefix('razer.').replace('.','_')].append(m)
lines=['//! Generated by tools/generate.py; protocol facts from docs/protocol.json.', '#![allow(clippy::type_complexity)]']
all_names=[]
for module, methods in groups.items():
    lines += [f'pub mod {module} {{', 'use crate::Method;']
    for m in methods:
        name=snake(m['name']).upper();all_names.append(f'{module}::{name}.info()')
        lines += [f'/// `{m["interface"]}.{m["name"]}`: `{m["input"]}` → `{m["output"]}`.',
                  f'pub const {name}: Method<{tup(types(m["input"]))}, {tup(types(m["output"]))}> = Method::new("{m["interface"]}", "{m["name"]}", "{m["input"]}", "{m["output"]}");']
    lines+=['}']
lines+=['/// Every audited method, including optional and legacy methods.', 'pub const ALL: &[crate::MethodInfo] = &[', ',\n'.join(all_names), '];']
pathlib.Path('src/methods.rs').write_text('\n'.join(lines)+'\n')
# A synthetic complete introspection fixture is a protocol regression oracle, not a real device.
from xml.etree.ElementTree import Element, SubElement, tostring
node=Element('node')
for module,methods in groups.items():
    iface=SubElement(node,'interface',name=methods[0]['interface'])
    for m in methods:
        method=SubElement(iface,'method',name=m['name'])
        for direction,key in [('in','input'),('out','output')]:
            sig=m[key]
            while sig:
                # Split complete D-Bus types, independently of Rust representation.
                i=0
                while sig[i]=='a':i+=1
                if sig[i]=='(':
                    depth=1;i+=1
                    while depth:
                        depth+=(sig[i]=='(')-(sig[i]==')');i+=1
                else:i+=1
                SubElement(method,'arg',type=sig[:i],direction=direction);sig=sig[i:]
pathlib.Path('tests/fixtures/all.xml').write_text(tostring(node,encoding='unicode')+'\n')
subprocess.run(['cargo','fmt'],check=True)
checks=['use openrazer::{Method, methods::*};', '''fn check<I, O>(method: &Method<I, O>)
where I: Default + serde::Serialize + zbus::wire::DynamicType,
      O: Default + serde::Serialize + zbus::wire::DynamicType {
    let _input = zbus::Message::method_call("/test", "Test").build(&I::default()).unwrap();
    let _output = zbus::Message::method_call("/test", "Test").build(&O::default()).unwrap();
    assert_eq!(I::default().signature().to_string_no_parens(), method.info().input, "input {:?}", method.info());
    assert_eq!(O::default().signature().to_string_no_parens(), method.info().output, "output {:?}", method.info());
}
#[test]
fn every_binding_serializes_exact_wire_argument_lists() {''']
for module,methods in groups.items():
    for m in methods:checks.append(f'check(&{module}::{snake(m["name"]).upper()});')
checks+=['}']
pathlib.Path('tests/wire_types.rs').write_text('// Generated by tools/generate.py\n'+'\n'.join(checks)+'\n')
subprocess.run(['cargo','fmt'],check=True)
